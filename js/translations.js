// LANGUAGE ENGINE

window.applyLanguage = function (language) {
    const dictionary = translations[language];

    if (!dictionary) return;

    document.documentElement.lang = language;
    document.documentElement.dataset.language = language;

    // Translate regular text without removing child elements
    document.querySelectorAll("[data-i18n]").forEach(element => {
        const key = element.dataset.i18n;

        if (Object.prototype.hasOwnProperty.call(dictionary, key)) {
            element.textContent = dictionary[key];
        }
    });

    // Translate placeholders
    document.querySelectorAll("[data-i18n-placeholder]").forEach(element => {
        const key = element.dataset.i18nPlaceholder;

        if (Object.prototype.hasOwnProperty.call(dictionary, key)) {
            element.placeholder = dictionary[key];
        }
    });

    // Translate document titles and accessible labels
    document.querySelectorAll("[data-i18n-aria]").forEach(element => {
        const key = element.dataset.i18nAria;

        if (Object.prototype.hasOwnProperty.call(dictionary, key)) {
            element.setAttribute("aria-label", dictionary[key]);
        }
    });

    // Translate button text while preserving its structure
    const languageButton = document.getElementById("language-toggle");

    if (languageButton) {
        languageButton.innerHTML = language === "es"
            ? "<strong>ES</strong> / EN"
            : "ES / <strong>EN</strong>";
    }

    // Preserve selected language
    try {
        localStorage.setItem("blackcore-language", language);
    } catch (error) {
        console.warn("Language preference could not be saved.");
    }

    window.currentLanguage = language;
};


// Initial language
window.getInitialLanguage = function () {
    try {
        const savedLanguage = localStorage.getItem("blackcore-language");

        return savedLanguage === "en" ? "en" : "es";
    } catch (error) {
        return "es";
    }
};
